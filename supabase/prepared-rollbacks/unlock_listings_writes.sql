-- ============================================================================
-- Снятие экстренной блокировки — парный файл к lock_listings_writes.sql.
-- ============================================================================
-- УСЛОВИЕ ВЫПОЛНЕНИЯ (не «frontend переключён» — недостаточно, см.
-- обоснование в lock_listings_writes.sql): выполнять ТОЛЬКО когда
--   (a) B (или спроектированная замена с эквивалентной проверкой) снова
--       применена и подтверждена своими собственными post-apply проверками,
--       ИЛИ
--   (b) отдельно спроектированный узкий guard применён (не подготовлено в
--       этом раунде).
-- Снятие раньше — до восстановления совместимой lifecycle-схемы — снова
-- открывает stale-вкладкам и прямым запросам путь писать status/is_active
-- без какой-либо проверки транзакций/ролей/лимитов, которую раньше давал
-- триггер B.
--
-- ВОССТАНОВЛЕНИЕ — ТОЧНО исходные права, не безусловный расширяющий GRANT.
-- Ниже воспроизведён снимок, зафиксированный ПЕРЕД REVOKE в
-- lock_listings_writes.sql на момент подготовки этого раунда (10th round,
-- локальная проверка): анон/authenticated имели ВСЕ семь типов —
-- SELECT, INSERT, UPDATE, DELETE, REFERENCES, TRIGGER, TRUNCATE. Если к
-- моменту реального отката снимок, сделанный ПЕРЕД lock в проде, отличается
-- от этого списка — восстанавливать ИМЕННО зафиксированный на тот момент
-- снимок, не этот файл вслепую.
-- ============================================================================

grant select, insert, update, delete, references, trigger, truncate
  on public.listings to authenticated, anon;

-- Проверка: сверить построчно с снимком "до REVOKE", сохранённым при
-- выполнении lock_listings_writes.sql в проде.
select grantee, privilege_type
from information_schema.role_table_grants
where table_name = 'listings' and grantee in ('authenticated', 'anon')
order by grantee, privilege_type;
