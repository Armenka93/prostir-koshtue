-- ============================================================================
-- Экстренная блокировка записи в listings — server-side circuit breaker
-- на время отката B. НЕ миграция, не в очереди migrations/ — обычный SQL,
-- запускается вручную (psql/SQL editor) с правами, достаточными для REVOKE.
-- ============================================================================
-- 10th round — ПРОВЕРЕНО ЛОКАЛЬНО реальным HTTP-запросом (не через frontend,
-- напрямую в PostgREST с anon key), не только прочитано в исходниках. См.
-- also_verified.md-эквивалент ниже в комментариях — точные результаты.
--
-- ЧТО РЕАЛЬНО ПРОВЕРЕНО (127.0.0.1:54321, реальный access token владельца):
--   PATCH listings {price:X}      (не трогает status/is_active) -> 403
--   PATCH listings {status:'X'}   (трогает status)               -> 403
--   POST rpc/adjust_listing_likes (SECURITY DEFINER, пишет likes) -> 204 (УСПЕХ)
--
-- ПОЧЕМУ REVOKE — НЕ гарантия блокировки ЛЮБОЙ записи (честно, не как было
-- заявлено раньше):
--   - PostgreSQL проверяет табличные GRANT до RLS — это реально блокирует
--     ЛЮБОЙ прямой PostgREST-запрос (INSERT/UPDATE/DELETE через REST API),
--     от старой вкладки, новой вкладки или curl/Postman с anon-ключом.
--   - НЕ блокирует SECURITY DEFINER RPC, исполняемые с правами ВЛАДЕЛЬЦА
--     функции (postgres), а не вызывающей роли — REVOKE у anon/authenticated
--     на это не действует в принципе. В проекте таких RPC, пишущих в
--     listings, три: adjust_listing_likes, increment_listing_views (прямые
--     RPC) и sync_listing_likes (триггер на таблице favorites). Проверено
--     чтением исходников (pg_get_functiondef) — ВСЕ ТРИ трогают только
--     likes/views, ни один никогда не пишет status/is_active/lifecycle-поля.
--     Поэтому для ЭТОЙ конкретной опасности (несовместимые lifecycle-записи
--     от старых вкладок) они не риск — но это факт, установленный проверкой
--     каждого конкретного RPC, а не общее свойство REVOKE.
--   - PUBLIC-грантов на listings отдельно от anon/authenticated/postgres/
--     service_role не обнаружено (проверено information_schema).
--   - anon/authenticated не состоят членами других ролей — обхода через
--     наследование нет (проверено pg_auth_members).
--   - Колоночные права ЗЕРКАЛЬНО повторяют табличные на момент проверки —
--     отдельного более широкого колоночного гранта, который пережил бы
--     табличный REVOKE, не найдено.
--
-- ПОЧЕМУ НЕ "точечная" блокировка только колонки status (рассматривалось и
-- ОТКЛОНЕНО после реальной проверки): `revoke update (status) on listings`
-- НЕ сужает уже существующий табличный `grant update` — они независимы в
-- PostgreSQL, табличный grant побеждает. Чтобы колоночная блокировка
-- работала, пришлось бы сначала снять табличный UPDATE целиком и выдать его
-- явно по каждой колонке, кроме status — но тогда одинаково блокируются и
-- опасные (submit/approve/reject/значимая правка) И легитимные
-- (archive/pause/restore — dbSetListingStatus тоже пишет status) запросы:
-- обе категории пишут status в одни и те же значения ('active'/'archived'/
-- 'paused'), различить их можно было только бизнес-логикой триггера B,
-- которого как раз и не будет. Точечного грант-based решения не существует —
-- полная блокировка ВСЕЙ записи в listings на время окна остаётся
-- единственным подтверждённым вариантом.
--
-- УСЛОВИЕ БЕЗОПАСНОЙ РАЗБЛОКИРОВКИ (не «frontend переключён» — этого
-- недостаточно, см. следующий блок ниже):
--
-- Редеплой frontend на flag=false НЕ эвакуирует уже открытые вкладки со
-- старым (flag=true) бандлом в памяти браузера — они продолжают звать
-- dbSubmitListingForReview/dbApproveListing/dbRejectListing/
-- dbUpdateListingForReview напрямую в Supabase тем же anon-ключом, что и
-- любой другой клиент, независимо от того, что нового задеплоено. Снятие
-- этой блокировки ДО того, как несовместимая lifecycle-схема (B) снова
-- обеспечивает корректную обработку этих же четырёх вызовов, немедленно
-- открывает ровно ту дыру, которую блокировка должна закрывать.
--
-- Поэтому: снимать блокировку ТОЛЬКО когда выполнено одно из:
--   (a) B (или спроектированная замена с эквивалентной проверкой лайфцикла)
--       снова применена и подтверждена — обычный путь вперёд после
--       исправления причины отката;
--   (b) явно спроектирован и применён отдельный, более узкий guard,
--       специфично блокирующий несовместимые переходы (status->
--       'pending_review' и approve/reject из pending_review) при этом не
--       трогающий archive/pause/restore — НЕ подготовлено в этом раунде,
--       требует отдельного проектирования триггера, не только GRANT.
-- До этого момента запись в listings остаётся ПОЛНОСТЬЮ заблокированной —
-- это сознательный, ограниченный по времени compromise (archive/pause/
-- restore/обычная правка черновика тоже недоступны любому пользователю на
-- время окна), а не частичная защита, которую нечем гарантировать.
--
-- Порядок использования:
--   1. Выполнить этот файл — ДО начала применения компенсирующей миграции.
--   2. Применить компенсирующую миграцию (восстанавливает состояние "A без B").
--   3. НЕ снимать блокировку по факту переключения frontend — см. условие
--      выше. unlock_listings_writes.sql содержит эту же проверку явно.

-- Снимок ТЕКУЩИХ прав — сохранить вывод перед REVOKE, использовать при
-- восстановлении вместо предположений о том, что "должно быть".
select grantee, privilege_type
from information_schema.role_table_grants
where table_name = 'listings' and grantee in ('authenticated', 'anon')
order by grantee, privilege_type;

revoke insert, update, delete on public.listings from authenticated, anon;

-- Проверка: подтвердить, что права действительно сняты.
select grantee, privilege_type
from information_schema.role_table_grants
where table_name = 'listings' and grantee in ('authenticated', 'anon')
order by grantee, privilege_type;
-- Ожидается: только SELECT, REFERENCES, TRIGGER, TRUNCATE (без INSERT/UPDATE/DELETE).
